#!/usr/bin/env node
// Writes docs/exports.md: which Mono exports each e2e runtime has, and which functions the library
// calls are missing where. Needs the runtime images and binutils' `nm`.
//
//   node scripts/exports-report.mjs

import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, relative, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const runtimes = JSON.parse(readFileSync(join(root, 'test/e2e/runtimes.json'), 'utf8'))
const work = mkdtempSync(join(tmpdir(), 'frida-mono-exports-'))

/** The file that exports the runtime: the `.so` a Unity host loads, else the `mono` executable. */
function runtimeBinary(runtime) {
  const library = runtime.run?.split(/\s+/).find((part) => part.endsWith('.so'))
  const path = library ?? '$(readlink -f "$(command -v mono)")'
  const out = join(work, `${runtime.name}.bin`)
  writeFileSync(out, execFileSync('docker', ['run', '--rm', '--entrypoint', 'sh', runtime.image, '-c', `cat ${path}`], { maxBuffer: 1 << 30 }))
  return out
}

function exportsOf(binary) {
  const text = execFileSync('nm', ['-D', '--defined-only', binary], { encoding: 'utf8', maxBuffer: 1 << 28 })
  return new Set(
    text
      .split('\n')
      .map((line) => line.trim().split(/\s+/))
      .filter((parts) => parts.length === 3 && /[TtWi]/.test(parts[1]) && parts[2].startsWith('mono_'))
      .map((parts) => parts[2].replace(/@.*$/, ''))
  )
}

function sourceFiles(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const path = join(dir, entry)
    return statSync(path).isDirectory() ? sourceFiles(path) : path.endsWith('.ts') && !path.endsWith('.generated.ts') ? [path] : []
  })
}

/** API functions the library calls, with the files calling them. */
const used = new Map()
for (const file of sourceFiles(join(root, 'src'))) {
  for (const match of readFileSync(file, 'utf8').matchAll(/api\.(mono_[a-z0-9_]+)/g)) {
    if (!used.has(match[1])) used.set(match[1], new Set())
    used.get(match[1]).add(relative(root, file))
  }
}

const table = readFileSync(join(root, 'src/native/api.generated.ts'), 'utf8')
const declared = new Set([...table.matchAll(/^ {2}(mono_\w+): \{/gm)].map((m) => m[1]))

const rows = []
const exportsByRuntime = new Map()
for (const runtime of runtimes) {
  console.log(`${runtime.name}: reading exports from ${runtime.image}`)
  try {
    exportsByRuntime.set(runtime.name, exportsOf(runtimeBinary(runtime)))
  } catch (error) {
    console.warn(`  skipped: ${error.message.split('\n')[0]}`)
  }
}

const names = [...exportsByRuntime.keys()]
const lines = []
lines.push('# Mono exports per runtime')
lines.push('')
lines.push('Generated by `node scripts/exports-report.mjs` from the e2e runtime images. Do not edit.')
lines.push('')
lines.push('| Runtime | `mono_*` exports | of the generated API table | `mono_unity_*` | used by frida-mono but missing |')
lines.push('|---|---|---|---|---|')
for (const name of names) {
  const exports = exportsByRuntime.get(name)
  const missing = [...used.keys()].filter((f) => !exports.has(f))
  lines.push(
    `| ${name} | ${exports.size} | ${[...declared].filter((f) => exports.has(f)).length} / ${declared.size} | ${[...exports].filter((f) => f.startsWith('mono_unity_')).length} | ${missing.length} |`
  )
  rows.push({ name, missing })
}
lines.push('')
lines.push('## Functions frida-mono calls that some runtime lacks')
lines.push('')
const gaps = [...used.keys()].filter((f) => names.some((n) => !exportsByRuntime.get(n).has(f))).sort()
if (gaps.length === 0) lines.push('None.')
else {
  lines.push(`| Function | ${names.join(' | ')} | Called from |`)
  lines.push(`|---|${names.map(() => '---').join('|')}|---|`)
  for (const f of gaps) lines.push(`| \`${f}\` | ${names.map((n) => (exportsByRuntime.get(n).has(f) ? '✓' : '✗')).join(' | ')} | ${[...used.get(f)].join(', ')} |`)
}
lines.push('')
lines.push(`frida-mono calls ${used.size} distinct API functions.`)
lines.push('')

mkdirSync(join(root, 'docs'), { recursive: true })
writeFileSync(join(root, 'docs/exports.md'), lines.join('\n'))
console.log(`Wrote docs/exports.md (${gaps.length} function(s) missing somewhere)`)
